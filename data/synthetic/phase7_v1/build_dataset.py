def write_jsonl(name, rows):
    (ROOT / name).write_text(''.join(json.dumps(row, ensure_ascii=False, sort_keys=True) + '\n' for row in rows), encoding='utf-8', newline='\n')

def build_core():
    (ROOT / 'docs').mkdir(exist_ok=True)
