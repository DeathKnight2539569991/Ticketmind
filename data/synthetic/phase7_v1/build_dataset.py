def cells(value):
    return [item.strip() for item in value.strip().split(';') if item.strip()]

def doc_refs(value):
    return [f'{item.split("/")[0]}:{int(item.split("/")[1]):03d}:001' for item in cells(value)]

def build_tests():
    rows = [line.split('|') for line in TEST_TEXT.strip().splitlines()]
    assert len(rows) == 48 and all(len(row) == 10 for row in rows)
    tickets, labels, plan = [], [], []
    for index, row in enumerate(rows):
        subject, body, questions, relevant, distractors, docs, doc_distractors, profile, rationale, forbidden = row
        test_id = f'SYN-P7-TEST-{index + 1:03d}'
        topic = DOCS[index // 6][0]
        within = index % 6
        action = ['propose_resolution', 'ask_clarification', 'escalate'][within // 2]
        tickets.append(dict(case_id=test_id, synthetic=True, group_id=f'phase7_{topic}', split='test',
            scenario_type=['positive', 'missing', 'risk'][within // 2],
            input=dict(subject=subject, body=body, channel=['web', 'email', 'api'][index % 3],
                requester_role='viewer' if index == 19 else '项目成员')))
        rule = 'P' + str(index // 6 + 1).zfill(2)
        safety = within >= 4
        rule_ids = ['G01', 'G02', ['G03', 'G04', 'G05'][within // 2], rule]
        if safety and rule != 'P08':
            rule_ids.append('P08')
        if index in (4, 28):
            rule_ids.append('G07')
        if index in (10, 11, 47):
            rule_ids.append('G08')
        if index in (35, 37, 38, 40):
            rule_ids.append('G06')
        labels.append(dict(case_id=test_id, label_status='pending_review', expected_action=action,
            relevant_source_ids=[f'SYN-P7-CASE-{int(value):03d}' for value in cells(relevant)],
            distractor_source_ids=[f'SYN-P7-CASE-{int(value):03d}' for value in cells(distractors)],
            relevant_doc_chunk_ids=doc_refs(docs), distractor_doc_chunk_ids=doc_refs(doc_distractors),
            answer_available=within < 2, human_review_required=True, requires_human_handoff=safety,
            necessary_questions=cells(questions), forbidden_conclusions=cells(forbidden),
            rationale=rationale + ' 所有路径均在固定Case bootstrap之后，空路径不表示零检索。',
            rule_ids=rule_ids, allowed_followup_tool_paths=PATHS[profile]))
        plan.append(dict(case_id=test_id, synthetic=True, evidence_profile=profile,
            bootstrap='fixed_case_search_always',
            profile_definition=('实质政策答案须来自Docs，bootstrap案例仍检索。' if profile == 'doc_only'
                else '案例可支持答案，不禁止合理文档补查。' if profile == 'case_only'
                else 'bootstrap匹配时无需追加工具，也接受合理补查。' if profile == 'no_extra_tools'
                else '案例方向与文档条件互补，实际必要性取决于已检索证据。'),
            query_rewrite_candidate=index in (1, 19, 25, 31, 37, 42, 43),
            query_rewrite_hint=('将客户别名/口语改写为文档概念，不复制标签答案。' if index in (1, 19, 25, 31, 37, 42, 43) else None),
            paired_with=f'SYN-P7-TEST-{(index // 6 * 6 + (3 if within < 2 else 1)):03d}',
            review_status='pending_review'))
    write_jsonl('evaluation_cases.jsonl', tickets)
    write_jsonl('evaluation_labels.jsonl', labels)
    write_jsonl('evaluation_annotations.jsonl', plan)

